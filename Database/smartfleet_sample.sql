CREATE FUNCTION public."MarkCriticalTasks"() RETURNS integer
    LANGUAGE plpgsql
    AS $$
DECLARE
    marked_count integer := 0;
BEGIN
    WITH changed AS (
        UPDATE public."TransportTasks" t
        SET
            "TaskStatus" = 'CRITICAL',
            "CriticalAt" = CURRENT_TIMESTAMP

        WHERE t."TaskStatus" = 'QUEUED'
          AND EXISTS (
              SELECT 1
              FROM public."TruckTaskLinks" l
              JOIN public."TruckVisits" v
                ON v."TruckVisitID" = l."TruckVisitID"

              WHERE l."TaskID" = t."TaskID"
                AND v."VisitStatus" IN ('WAITING','LOADING')
                AND v."ActualDepartureAt" IS NULL
                AND CURRENT_TIMESTAMP >= (
                    v."PlannedDepartureAt"
                    - make_interval(
                        mins => v."CriticalThresholdMinutes"
                    )
                )
          )

        RETURNING t."TaskID"
    ),

    history_written AS (
        INSERT INTO public."TaskStatusHistories" (
            "TaskID",
            "PreviousStatus",
            "NewStatus",
            "ChangedBy",
            "Reason",
            "ChangedAt"
        )
        SELECT
            "TaskID",
            'QUEUED',
            'CRITICAL',
            NULL,
            'Truck deadline reached critical threshold',
            CURRENT_TIMESTAMP
        FROM changed
        RETURNING 1
    )

    SELECT COUNT(*)
    INTO marked_count
    FROM history_written;

    RETURN marked_count;
END;
$$;




