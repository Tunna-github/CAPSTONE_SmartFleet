-- Additive migration: preserves existing missions and their historical results.
-- Apply before starting the backend version that requires FE07 verification.
BEGIN;
-- Frozen routes may contain up to 100 waypoints; the old 4 KB limit was for CIRCLE commands.
ALTER TABLE public."RobotCommandOutbox" ALTER COLUMN "Payload" TYPE text;
CREATE TABLE IF NOT EXISTS public."MissionExecutions" (
    "MissionId" bigint PRIMARY KEY REFERENCES public."Missions"("MissionID"),
    "RoutePayloadJson" text NOT NULL CHECK ("RoutePayloadJson" IS JSON),
    "MapRevision" integer NOT NULL,
    "NextWaypointIndex" integer NOT NULL DEFAULT 0 CHECK ("NextWaypointIndex" >= 0),
    "ExpectedPickupQr" text NOT NULL,
    "ExpectedDeliveryQr" text NOT NULL,
    "PackageCode" text,
    "StationPresenceAt" timestamptz,
    "Revision" integer NOT NULL DEFAULT 0,
    "UpdatedAt" timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS public."VerificationAttempts" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MissionId" bigint NOT NULL REFERENCES public."Missions"("MissionID"),
    "RequestId" text NOT NULL,
    "RequestHash" text NOT NULL,
    "Stage" text NOT NULL CHECK ("Stage" IN ('PICKUP','DELIVERY')),
    "Type" text NOT NULL CHECK ("Type" IN ('QRCODE','MANUAL')),
    "ScannedQr" text,
    "ScannedPackageCode" text,
    "ExpectedQr" text NOT NULL,
    "Accepted" boolean NOT NULL,
    "Result" text NOT NULL,
    "Note" text,
    "UserId" integer NOT NULL REFERENCES public."Users"("UserID"),
    "CreatedAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_VerificationAttempts_MissionId_RequestId"
    ON public."VerificationAttempts" ("MissionId","RequestId");
ALTER TABLE public."RobotQrScanEvents" ADD COLUMN IF NOT EXISTS "EventId" text;
ALTER TABLE public."RobotQrScanEvents" ADD COLUMN IF NOT EXISTS "WaypointIndex" integer;
CREATE UNIQUE INDEX IF NOT EXISTS "IX_RobotQrScanEvents_RobotId_EventId"
    ON public."RobotQrScanEvents" ("RobotID","EventId") WHERE "EventId" IS NOT NULL;
COMMIT;
